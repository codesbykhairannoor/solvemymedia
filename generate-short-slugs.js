import fs from 'fs';
import path from 'path';
import translate from 'google-translate-api-x';
import anyAscii from 'any-ascii';

const langs = [
  'id','es','fr','de','it','pt','nl','pl','ru',
  'ja','ko','zh','zh-TW','tr','vi','th','ar','hi','sv',
  'no','da','fi','cs','hu','el','ro','uk','ms','tl'
];

const langMap = {
  'zh': 'zh-cn',
  'zh-TW': 'zh-tw'
};

const baseStrings = [
  "Compress Video", "Compress Audio", "Convert Video", "Convert Audio",
  "Video to Audio", "Transcribe Media", "Studio Recorder", "Create GIF",
  "Change Speed", "Crop Video", "Mute Video", "Add Watermark", "Merge Audio"
];

const toolIds = [
  "compress-video", "compress-audio", "convert-video", "convert-audio",
  "video-to-audio", "transcribe", "recorder", "create-gif",
  "video-speed", "crop-video", "mute-video", "watermark-video", "merge-audio"
];

const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));

function slugify(text) {
  return anyAscii(text)
    .toString()
    .toLowerCase()
    .trim()
    .replace(/[\s_'-]+/g, '-')
    .replace(/[^\w-]/g, '') // STRICTLY ASCII ONLY!
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '');
}

async function run() {
  const TOOL_SLUGS = {};
  for (const t of toolIds) TOOL_SLUGS[t] = { en: t };

  const DELIM = ' _|||_ ';
  const joined = baseStrings.join(DELIM);

  console.log("Starting translation for safe short slugs in 30 languages...");

  for (let i = 0; i < langs.length; i++) {
    const lang = langs[i];
    const targetLang = langMap[lang] || lang;
    console.log(`[${i+1}/${langs.length}] Translating to ${lang}...`);
    
    let retries = 3;
    let translatedStrings = baseStrings;
    while(retries > 0) {
      try {
        const res = await translate(joined, { to: targetLang });
        let translatedArray = res.text.split(DELIM);
        if (translatedArray.length !== baseStrings.length) {
          translatedArray = res.text.split(/_\|\|\|_|_ \|\|\| _/g).map(s => s.trim());
        }
        if (translatedArray.length === baseStrings.length) {
          translatedStrings = translatedArray;
        } else {
          console.error(`Delimiter mismatch for ${lang}.`);
        }
        break;
      } catch (e) {
        retries--;
        console.error(`Error translating to ${lang}. Retries left: ${retries}`);
        await sleep(2000);
      }
    }
    
    for (let j = 0; j < baseStrings.length; j++) {
       let s = slugify(translatedStrings[j]);
       if (!s) s = toolIds[j];
       TOOL_SLUGS[toolIds[j]][lang] = s;
    }
    await sleep(500); 
  }

  let fileContent = `// AUTO-GENERATED: Do not edit manually. Generated by generate-short-slugs.js\n\n`;
  fileContent += `export const TOOL_SLUGS: Record<string, Record<string, string>> = ${JSON.stringify(TOOL_SLUGS, null, 2)};\n\n`;
  
  fileContent += `export const getSlug = (toolId: string, lang: string): string => {\n`;
  fileContent += `  return TOOL_SLUGS[toolId]?.[lang] || toolId;\n`;
  fileContent += `};\n\n`;
  
  fileContent += `export const getLocalizedPath = (toolId: string, lang: string): string => {\n`;
  fileContent += `  const slug = getSlug(toolId, lang);\n`;
  fileContent += `  if (lang === 'en') return \`/\${slug}\`;\n`;
  fileContent += `  return \`/\${lang}/\${slug}\`;\n`;
  fileContent += `};\n\n`;

  fileContent += `export const resolveSlug = (slug: string, urlLang?: string): { toolId: string, lang: string } | null => {\n`;
  fileContent += `  if (urlLang) {\n`;
  fileContent += `    for (const [toolId, langs] of Object.entries(TOOL_SLUGS)) {\n`;
  fileContent += `      if (langs[urlLang] === slug) return { toolId, lang: urlLang };\n`;
  fileContent += `    }\n`;
  fileContent += `  }\n`;
  fileContent += `  for (const [toolId, langs] of Object.entries(TOOL_SLUGS)) {\n`;
  fileContent += `    for (const [l, s] of Object.entries(langs)) {\n`;
  fileContent += `      if (s === slug) return { toolId, lang: l };\n`;
  fileContent += `    }\n`;
  fileContent += `  }\n`;
  fileContent += `  return null;\n`;
  fileContent += `};\n`;

  const srcDir = 'd:/audiovideo/media-compressor/src/utils';
  fs.writeFileSync(path.join(srcDir, 'urlSlugs.ts'), fileContent);
  console.log("Successfully generated fully translated short urlSlugs.ts!");
}

run().catch(console.error);
